/**
 * 把矩阵转为便于比对的字符串数组。
 * @param modules 模块矩阵
 * @returns 每行一个 "0"/"1" 字符串
 */
function toRows(modules: readonly (readonly boolean[])[]): string[] {
    return modules.map(row => row.map(dark => (dark ? "1" : "0")).join(""))
}

describe("createQrCode", () => {
    it("与独立实现的参考矩阵逐模块一致", () => {
        expect(REFERENCE_VECTORS.length).toBeGreaterThan(0)
        for (const vector of REFERENCE_VECTORS) {
            const qr = createQrCode(vector.text, { ecc: vector.ecc, mask: vector.mask })
            expect(qr.version, vector.label).toBe(vector.version)
            expect(qr.size, vector.label).toBe(vector.rows.length)
            expect(toRows(qr.modules), vector.label).toEqual(vector.rows)
        }
    })

    it("按内容长度自动选择最小版本", () => {
        expect(createQrCode("A").version).toBe(1)
        expect(createQrCode("a".repeat(17), { ecc: "M" }).version).toBe(2)
        // 同一内容在高纠错等级下需要更大的版本
        const low = createQrCode("a".repeat(40), { ecc: "L" })
        const high = createQrCode("a".repeat(40), { ecc: "H" })
        expect(high.version).toBeGreaterThan(low.version)
    })

    it("内容超出容量时抛错", () => {
        expect(() => createQrCode("a".repeat(3000), { ecc: "H", minVersion: 1, maxVersion: 10 })).toThrow(/过长/)
    })

    it("自动掩码取值合法", () => {
        const qr = createQrCode("https://dna-builder.cn/download")
        expect(qr.mask).toBeGreaterThanOrEqual(0)
        expect(qr.mask).toBeLessThanOrEqual(7)
        expect(qr.ecc).toBe("M")
    })

    it("绘制规范要求的功能图形", () => {
        const qr = createQrCode("https://dna-builder.cn/download", { mask: 0 })

        // 三个 7×7 定位图形：外圈深色、第二圈浅色、中间 3×3 深色
        const finderAt = (ox: number, oy: number) => {
            for (let y = 0; y < 7; y++) {
                for (let x = 0; x < 7; x++) {
                    const expectDark = Math.max(Math.abs(x - 3), Math.abs(y - 3)) !== 2
                    expect(qr.modules[oy + y][ox + x], `定位图形 (${ox},${oy}) 内 (${x},${y})`).toBe(expectDark)
                }
            }
        }
        for (const origin of qr.finderOrigins) {
            finderAt(origin.x, origin.y)
        }

        // 时序图形：第 6 行/列自 (6,6) 起深浅交替
        for (let i = 8; i < qr.size - 8; i++) {
            expect(qr.modules[6][i]).toBe(i % 2 === 0)
            expect(qr.modules[i][6]).toBe(i % 2 === 0)
        }

        // 右下固定深色模块
        expect(qr.modules[qr.size - 8][8]).toBe(true)

        // 格式信息：第一份副本按 bit0→bit14 落在这些模块上（M 级 + 掩码 0 的已知值为 0x5412）
        const formatModules: [number, number][] = [
            [8, 0],
            [8, 1],
            [8, 2],
            [8, 3],
            [8, 4],
            [8, 5],
            [8, 7],
            [8, 8],
            [7, 8],
            [5, 8],
            [4, 8],
            [3, 8],
            [2, 8],
            [1, 8],
            [0, 8],
        ]
        const formatBits = formatModules.reduce((acc, [x, y], index) => acc | ((qr.modules[y][x] ? 1 : 0) << index), 0)
        expect(formatBits).toBe(0b101010000010010)
    })

    it("给出定位图形与校正图形布局", () => {
        const v1 = getQrCodeLayout(1)
        expect(v1.finderOrigins).toEqual([
            { x: 0, y: 0 },
            { x: 14, y: 0 },
            { x: 0, y: 14 },
        ])
        expect(v1.alignmentCenters).toEqual([])

        // 版本 7：3 个校正坐标两两组合去掉 3 个角落，共 6 个校正图形
        const v7 = getQrCodeLayout(7)
        expect(v7.alignmentCenters).toHaveLength(6)
        expect(v7.finderOrigins[1]).toEqual({ x: 38, y: 0 })
        expect(v7.alignmentCenters).toContainEqual({ x: 6, y: 22 })
        expect(v7.alignmentCenters).toContainEqual({ x: 22, y: 22 })
    })
})
