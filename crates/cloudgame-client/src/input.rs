/// winit MouseButton → input_op code。
pub fn mouse_op(btn: winit::event::MouseButton) -> Option<i32> {
    Some(match btn {
        winit::event::MouseButton::Left => crate::proto::z3::LEFT,
        winit::event::MouseButton::Middle => crate::proto::z3::MIDDLE,
        winit::event::MouseButton::Right => crate::proto::z3::RIGHT,
        winit::event::MouseButton::Back => crate::proto::z3::XBUTTON1_BACK,
        winit::event::MouseButton::Forward => crate::proto::z3::XBUTTON2_FORWARD,
        _ => return None,
    })
}
