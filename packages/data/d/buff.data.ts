/**
 * BUFF 数值：以值类型判定静态/动态。
 * number 为静态满级值（按 a/b 等级公式缩放），number[] 为各等级绝对值（mx/lx 档位），
 * string 为动态表达式（随属性上下文求值，如 `"0.8*技能威力"`）。
 */
export type BuffAttrValue = number | number[] | string

export interface Buff {
    id?: number
    名称: string
    /** 展示文案：buff.data 的 BUFF 自带描述；effect.data 的特效不存描述，展示走武器 `熔炼` / MOD `效果` */
    描述?: string
    /** BUFF：角色 id；特效：元素名（旧存档可能为角色名） */
    限定?: string | number
    a?: number
    b?: number
    dx?: number
    lx?: number
    mx?: number
    code?: string
    /** 条件BUFF（技能限定）：只作用于名称匹配该模式的字段（支持 "|" 交替多技能，如 "月猎|日食"），不参与全局属性汇总 */
    技能?: string
    /** 条件BUFF（字段标签限定）：只作用于 tag 包含任一限定标签的字段（如 ["充盈"]），不参与全局属性汇总 */
    tag?: string[]
    /**
     * 互斥魔之楔：装备列表内任一 MOD 时本 BUFF 失效（同名增益已由 MOD 提供，避免重复计算）。
     * 例：`羽翼·鼓舞·昂扬(雷)` 与 海妖「羽翼·鼓舞·昂扬」/ 换生灵「昂扬」互斥。
     */
    禁用?: number[]
    /** 数值表：静态值与动态表达式混存（特效表以 `@` 前缀声明归属 BUFF 层的属性） */
    attr?: Record<string, BuffAttrValue>
    display?: Record<string, string>
}

